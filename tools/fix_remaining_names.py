#!/usr/bin/env python3
"""Fix remaining names without definitions."""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

BASE_DIR = Path(__file__).parent.parent

with open(BASE_DIR / 'data' / 'bible_names.json', 'r', encoding='utf-8') as f:
    data = json.load(f)
names = data['names']

ns = 'http://openscriptures.github.com/morphhb/namespace'
tree = ET.parse(r'C:\Users\Tammy Casey\Documents\AI PROJECTS\PEER\morphhb-master\HebrewStrong.xml')
root = tree.getroot()

def ft(e):
    if e is None: return ''
    parts = [e.text or '']
    for c in e:
        parts.append(c.text or '')
        parts.append(c.tail or '')
    return re.sub(r'\s+', ' ', ' '.join(parts)).strip()

strongs = {}
for entry in root:
    sid = entry.attrib.get('id', '')
    if not sid: continue
    w = entry.find(f'{{{ns}}}w')
    source = entry.find(f'{{{ns}}}source')
    meaning = entry.find(f'{{{ns}}}meaning')
    usage = entry.find(f'{{{ns}}}usage')
    strongs[sid] = {
        'hebrew': (w.text or '').strip() if w is not None else '',
        'pron': w.attrib.get('pron', '') if w is not None else '',
        'xlit': w.attrib.get('xlit', '') if w is not None else '',
        'source_text': ft(source),
        'meaning': ft(meaning),
        'usage': ft(usage),
    }

# Build ALL lookups
all_by_hebrew = {}
for sid, e in strongs.items():
    clean = re.sub(r'[\u0591-\u05C7]', '', e['hebrew'])
    if clean and clean not in all_by_hebrew:
        all_by_hebrew[clean] = sid

all_by_english = {}
for sid, e in strongs.items():
    for field in ['usage', 'meaning']:
        text = e.get(field, '')
        for eng in re.findall(r'([A-Z][a-z]{2,})', text):
            if eng not in all_by_english:
                all_by_english[eng] = sid

