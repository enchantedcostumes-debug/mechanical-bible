fixed = 0
still_missing = []

for i, n in enumerate(names):
    if n.get('definition'):
        continue
    eng = n.get('english', '')
    heb = n.get('hebrew', '')

    if eng in MANUAL:
        names[i]['definition'] = MANUAL[eng]
        fixed += 1
    elif heb in all_by_hebrew:
        sid = all_by_hebrew[heb]
        se = strongs[sid]
        m = se.get('meaning', '') or se.get('usage', '')
        if m:
            m = re.sub(r'^[^,]+,\s*', '', m).strip()
            if m and len(m) > 2:
                names[i]['definition'] = m[0].upper() + m[1:]
                names[i]['strongs'] = sid
                if se['pron']: names[i]['pronunciation'] = se['pron']
                if se['xlit']: names[i]['transliteration'] = se['xlit']
                fixed += 1
                continue
        still_missing.append(eng)
    else:
        # Gentilics
        base = re.sub(r'(ites?|ans?|eans?|ish)$', '', eng)
        if base != eng and len(base) > 2:
            names[i]['definition'] = f'Of/from {base}.'
            fixed += 1
        else:
            still_missing.append(eng)

has_def = sum(1 for n in names if n.get('definition'))
print(f'Fixed {fixed} more names')
print(f'Still missing: {len(still_missing)}')
if still_missing:
    print(f'Missing: {still_missing}')
print(f'Final: {has_def}/{len(names)} with definitions ({has_def/len(names)*100:.1f}%)')

data['names'] = names
with open(BASE_DIR / 'data' / 'bible_names.json', 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)
print('Saved.')
